import { ChatOllama} from "@langchain/ollama";
import { ChatPromptTemplate } from "@langchain/core/prompts";

export async function generateAnswer(question: string, context: string){


    const totalStart = Date.now();

    const modelStart = Date.now();

    // configure the LLM we want LangChain to use

    //PURPOSE:
    // create a LangChain model object that knows how to talk to our locally running Ollama model

    // Ollama -> llama3.2:3b -> running locally on our computer

    const model = new ChatOllama({
        model: 'llama3.2:3b',
        temperature: 0
    })

    console.log(
        "model creation:",
        Date.now() - modelStart, "ms"
    )

    const promptStart = Date.now();

    const prompt = ChatPromptTemplate.fromMessages([ 
        ['system','Answer using only the PDF context. If the answer is not in the content, say you cannot find it'],
        [
            "human",
            "CONTEXT:\n{context}\n\nQUESTION:\n{question}"
        ]
    ]);

    console.log("prompt creation:", Date.now() - promptStart, "ms");


    const formattingStart = Date.now();

    const formatted = await prompt.formatMessages({
        context: context,
        question: question
    })

    console.log("prompt formatting", Date.now() - formattingStart);
    console.log("context characters:", context.length);
    console.log("question characters:", question.length);

    // send the finished prompt to Llama

    // INPUT:
    // formatted messages containing:
    // - instructions
    // - PDF context
    // - user's question

    // OUTPUT:
    // response -> AIMessage
    const invokeStart = Date.now();

const response = await model.invoke(formatted);

console.log(
    "model invoke:",
    Date.now() - invokeStart,
    "ms"
);

console.log(
    "response characters:",
    String(response.content).length
);

console.log(
    "response metadata:",
    response.response_metadata
);

console.log(
    "usage metadata:",
    response.usage_metadata
);

console.log("model invoke:", Date.now() - invokeStart, "ms")


console.log("generateAnswer Total:", Date.now() - totalStart, "ms");


// return only the text generated by the LLM
return response.content;
}


